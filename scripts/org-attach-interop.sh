#!/usr/bin/env bash
# Checks Bloom's attachment-dir resolution against real Emacs org-attach.
#
# For every case in app/src/test/resources/attach/org-attach-cases.tsv, builds the
# listed directories in a temp dir, runs (org-attach-dir-from-id ID 'existing)
# under `emacs --batch`, and prints the case plus Emacs' answer (relative to the
# org file's directory). The output is diffed against the committed golden file,
# which AttachDirResolverGoldenTest replays against Bloom's resolver in `./gradlew test`.
#
# It also checks owner precedence: for every app/src/test/resources/attach/owner/*.org,
# it opens the file, moves point to the `# point` line and runs
# (org-attach-dir nil t) with :DIR: / :ATTACH_DIR: inherited and :ID: not
# (org-attach-use-inheritance 'selective, org-use-property-inheritance
# '("DIR" "ATTACH_DIR")). The answers go to org-attach-owner-golden.tsv, which
# AttachOwnerGoldenTest replays.
#
# Usage:
#   scripts/org-attach-interop.sh            # diff Emacs output against the golden file
#   scripts/org-attach-interop.sh --update   # rewrite the golden file from Emacs
#
# ORG_LISP points at an Org checkout's lisp/ dir (default: straight.el's copy).
# Without it, Emacs' bundled Org is used.
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
cases="$root/app/src/test/resources/attach/org-attach-cases.tsv"
golden="$root/app/src/test/resources/attach/org-attach-golden.tsv"
owner_cases="$root/app/src/test/resources/attach/owner"
owner_golden="$root/app/src/test/resources/attach/org-attach-owner-golden.tsv"
org_lisp=${ORG_LISP:-$HOME/.emacs.d/straight/repos/org/lisp}

command -v emacs >/dev/null || { echo "emacs not found on PATH" >&2; exit 2; }

load_path=()
[ -d "$org_lisp" ] && load_path=(-L "$org_lisp")

out=$(mktemp)
owner_out=$(mktemp)
trap 'rm -f "$out" "$owner_out"' EXIT

emacs --batch -Q "${load_path[@]}" --eval '
(progn
  (require (quote org))
  (require (quote org-attach))
  (let* ((cases-file (car command-line-args-left))
         (tmp (make-temp-file "bloom-attach-" t)))
    (setq command-line-args-left nil)
    (with-temp-buffer
      (insert-file-contents cases-file)
      (dolist (line (split-string (buffer-string) "\n" t))
        (unless (string-prefix-p "#" line)
          (let* ((f (split-string line "\t"))
                 (name (nth 0 f))
                 (dir (file-name-as-directory (expand-file-name name tmp))))
            (make-directory dir t)
            (unless (equal (nth 3 f) "-")
              (dolist (d (split-string (nth 3 f) "," t))
                (make-directory (expand-file-name d dir) t)))
            (let* ((default-directory dir)
                   (org-attach-id-dir (nth 1 f))
                   (res (org-attach-dir-from-id (nth 2 f) t)))
              (princ (format "%s\t%s\n" line
                             (directory-file-name (file-relative-name res dir)))))))))
    (delete-directory tmp t)))' "$cases" > "$out"

emacs --batch -Q "${load_path[@]}" --eval '
(progn
  (require (quote org))
  (require (quote org-attach))
  (let* ((case-dir (car command-line-args-left))
         (tmp (make-temp-file "bloom-attach-owner-" t))
         (notes (file-name-as-directory (expand-file-name "notes" tmp)))
         (org-attach-id-dir "data/")
         (org-attach-use-inheritance (quote selective))
         (org-use-property-inheritance (quote ("DIR" "ATTACH_DIR"))))
    (setq command-line-args-left nil)
    (make-directory notes t)
    (dolist (src (directory-files case-dir t "\\.org$"))
      (let ((file (expand-file-name (file-name-nondirectory src) notes)))
        (copy-file src file t)
        (with-current-buffer (find-file-noselect file)
          (goto-char (point-min))
          (re-search-forward "^# point$")
          (let ((res (org-attach-dir nil t)))
            (princ (format "%s\t%s\n" (file-name-base file)
                           (if res (directory-file-name (file-relative-name (expand-file-name res) notes)) "-"))))
          (kill-buffer))))
    (delete-directory tmp t)))' "$owner_cases" > "$owner_out"

if [ "${1:-}" = "--update" ]; then
  {
    echo "# Generated by scripts/org-attach-interop.sh --update. Do not edit by hand."
    echo "# Columns: the case columns from org-attach-cases.tsv, then Emacs' attach dir relative to the org file's directory."
    cat "$out"
  } > "$golden"
  {
    echo "# Generated by scripts/org-attach-interop.sh --update. Do not edit by hand."
    echo "# Columns: fixture name in owner/, then Emacs' (org-attach-dir nil t) at the # point line, relative to the org file's directory (- for none)."
    cat "$owner_out"
  } > "$owner_golden"
  echo "Wrote $golden and $owner_golden"
else
  status=0
  if diff -u <(grep -v '^#' "$golden") "$out"; then
    echo "org-attach interop: Emacs matches the id golden file ($(wc -l < "$out" | tr -d ' ') cases)"
  else
    echo "org-attach interop: Emacs output differs from the id golden file" >&2
    status=1
  fi
  if diff -u <(grep -v '^#' "$owner_golden") "$owner_out"; then
    echo "org-attach interop: Emacs matches the owner golden file ($(wc -l < "$owner_out" | tr -d ' ') cases)"
  else
    echo "org-attach interop: Emacs output differs from the owner golden file" >&2
    status=1
  fi
  exit $status
fi
